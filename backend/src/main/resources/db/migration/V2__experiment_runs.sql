CREATE TABLE experiment_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    experiment_id CHAR(32) NOT NULL,
    run_number INTEGER NOT NULL,
    status VARCHAR(20) NOT NULL,
    started_at TIMESTAMP NOT NULL,
    ended_at TIMESTAMP,
    target_metric VARCHAR(40) NOT NULL,
    winner_code CHAR(1),
    conclusion TEXT,
    CONSTRAINT uq_experiment_runs_number UNIQUE (experiment_id, run_number),
    CONSTRAINT ck_experiment_runs_status CHECK (status IN ('activo', 'terminado', 'cancelado')),
    CONSTRAINT ck_experiment_runs_winner CHECK (winner_code IS NULL OR winner_code IN ('A', 'B')),
    CONSTRAINT ck_experiment_runs_dates CHECK (ended_at IS NULL OR ended_at >= started_at),
    CONSTRAINT fk_experiment_runs_experiment FOREIGN KEY (experiment_id) REFERENCES experiments (id)
);

CREATE TABLE experiment_run_variants (
    run_id BIGINT NOT NULL,
    code CHAR(1) NOT NULL,
    description TEXT NOT NULL,
    visits BIGINT,
    registrations BIGINT,
    activations BIGINT,
    conversions BIGINT,
    clicks BIGINT,
    spend DECIMAL(18, 2),
    measured_at TIMESTAMP,
    CONSTRAINT pk_experiment_run_variants PRIMARY KEY (run_id, code),
    CONSTRAINT ck_experiment_run_variants_code CHECK (code IN ('A', 'B')),
    CONSTRAINT ck_experiment_run_variants_description CHECK (LENGTH(TRIM(description)) > 0),
    CONSTRAINT ck_experiment_run_variants_visits CHECK (visits IS NULL OR visits >= 0),
    CONSTRAINT ck_experiment_run_variants_registrations CHECK (registrations IS NULL OR registrations >= 0),
    CONSTRAINT ck_experiment_run_variants_activations CHECK (activations IS NULL OR activations >= 0),
    CONSTRAINT ck_experiment_run_variants_conversions CHECK (conversions IS NULL OR conversions >= 0),
    CONSTRAINT ck_experiment_run_variants_clicks CHECK (clicks IS NULL OR clicks >= 0),
    CONSTRAINT ck_experiment_run_variants_spend CHECK (spend IS NULL OR spend >= 0),
    CONSTRAINT fk_experiment_run_variants_run FOREIGN KEY (run_id) REFERENCES experiment_runs (id)
);

CREATE INDEX ix_experiment_runs_experiment ON experiment_runs (experiment_id);
CREATE INDEX ix_experiment_runs_status ON experiment_runs (status);
CREATE INDEX ix_experiment_runs_dates ON experiment_runs (started_at, ended_at);
